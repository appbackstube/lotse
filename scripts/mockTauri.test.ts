import assert from "node:assert/strict";
import { invoke } from "@tauri-apps/api/core";
import { emit, emitTo, listen } from "@tauri-apps/api/event";
import { mockWindows } from "@tauri-apps/api/mocks";
import { getCurrentWindow } from "@tauri-apps/api/window";
import { mockIPC } from "./mockTauri.ts";

Object.assign(globalThis, { window: globalThis });
mockIPC((_command, payload) => payload, { shouldMockEvents: true });
assert.deepEqual(await invoke("ai_chat_steer", { input: { requestId: "turn" } }), { requestId: "turn" });
await assert.rejects(invoke("ai_chat_steer", { requestId: "turn" }), /requires an input object/);
let calls = 0;
const stop = await listen("test", () => calls++);
await emit("test");
stop();
await emit("test");
assert.equal(calls, 1, "Unlistened callbacks must be removed from the mock event registry");
const received: string[] = [];
const stopGlobal = await listen("targeted", () => received.push("global"));
mockWindows("main");
const stopMain = await getCurrentWindow().listen("targeted", () => received.push("main"));
mockWindows("other");
const stopOther = await getCurrentWindow().listen("targeted", () => received.push("other"));
await emitTo("main", "targeted");
assert.deepEqual(received, ["global", "main"], "Global listeners also receive events addressed to a window");
received.length = 0;
await emitTo("other", "targeted");
assert.deepEqual(received, ["global", "other"]);
received.length = 0;
await emit("targeted");
assert.deepEqual(received, ["global", "main", "other"], "Broadcasts still reach window listeners");
await stopMain();
received.length = 0;
await emitTo("main", "targeted");
assert.deepEqual(received, ["global"], "Disposed window listeners must not receive targeted events");
await stopGlobal();
await stopOther();
console.log("Tauri mock request contracts and listener disposal passed.");
