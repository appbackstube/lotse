import assert from "node:assert/strict";
import { scheduleDue, scheduleBlockReason, scheduledMessage, scheduleInterval, type PromptSchedule } from "../src/promptSchedules.ts";
import { normalizeTask } from "../src/tasks.ts";

const task = normalizeTask({ id: "12345678-1234-1234-1234-123456789abc", title: "Check", chatMode: "plan", attachments: [{ kind: "image", path: "/synthetic/draft.png", name: "draft.png" }] })!;
const schedule: PromptSchedule = { id: "s", repositoryRoot: "/repo", taskId: task.id, title: "Check again", prompt: "Check the build", runAt: 100, intervalMinutes: 60, enabled: true, nextRunAt: 100, runNowRequested: false, pauseReason: null, latestRun: null };
assert.equal(scheduleDue(schedule, 99), false);
assert.equal(scheduleDue(schedule, 100), true);
assert.equal(scheduleDue({ ...schedule, enabled: false }, 100), false);
assert.equal(scheduleDue({ ...schedule, enabled: false, runNowRequested: true }, 99), true);
assert.equal(scheduleDue({ ...schedule, nextRunAt: null }, 100), false);
assert.match(scheduleBlockReason(undefined, false, false)!, /no longer exists/);
assert.match(scheduleBlockReason({ ...task, completed: true }, false, false)!, /Done/);
assert.match(scheduleBlockReason(task, true, true)!, /queued messages/);
assert.match(scheduleBlockReason(task, true, false)!, /idle/);
assert.equal(scheduleBlockReason(task, false, false), null);
assert.throws(() => scheduledMessage(schedule, task), /claimed/);
const claimed: PromptSchedule = { ...schedule, latestRun: { id: "occurrence", status: "running", scheduledAt: 100, startedAt: 100, finishedAt: null, error: null } };
assert.equal(scheduleDue(claimed, 200), false);
const original = JSON.stringify(task);
const item = scheduledMessage(claimed, task);
assert.equal(item.id, "occurrence");
assert.equal(item.body, schedule.prompt);
assert.equal(item.mode, task.chatMode);
assert.equal(item.model, task.chatModel);
assert.equal(item.effort, task.chatEffort);
assert.equal(item.selection, null);
assert.deepEqual(item.context.attachments, []);
assert.equal(JSON.stringify(task), original, "scheduled messages must preserve pending task attachments");
assert.deepEqual([null, 1, 2, 60, 120, 1440, 2880].map(scheduleInterval), ["One-time", "Every 1 minute", "Every 2 minutes", "Every 1 hour", "Every 2 hours", "Every 1 day", "Every 2 days"]);
console.log("Prompt scheduler tests passed");
