import assert from "node:assert/strict";
import { mockIPC } from "@tauri-apps/api/mocks";

Object.assign(globalThis, { window: new EventTarget() });
const writes: { key: string; value: string | null }[] = [];
let fail = false;
mockIPC(async (command, args) => {
  assert.equal(command, "set_frontend_storage");
  assert.ok((args as typeof writes[number]).key.startsWith("chaoticreview."), "Native storage only accepts chaoticreview keys");
  if (fail) throw new Error("Synthetic disk failure");
  writes.push(args as typeof writes[number]);
});
const { fileStore } = await import("../src/fileStore.ts");
const { saveTasks, loadTasks, normalizeTask, taskStorageKey } = await import("../src/tasks.ts");
let serializations = 0;
for (let index = 0; index < 20; index++) fileStore.setJSON("chaoticreview.test", { toJSON() { serializations++; return { index }; } });
assert.equal(serializations, 0, "Typing must not serialize overwritten snapshots");
assert.equal(writes.length, 0);
await fileStore.flush();
assert.equal(serializations, 1);
assert.equal(writes.length, 1);
assert.deepEqual(JSON.parse(writes[0].value!), { index: 19 });

fileStore.setJSON("chaoticreview.test", { version: 2 });
assert.deepEqual(JSON.parse(fileStore.getItem("chaoticreview.test")!), { version: 2 }, "Pending edits must be readable before disk flush");
await new Promise((resolve) => setTimeout(resolve, 350));
assert.equal(writes.length, 2, "Deferred saves must eventually persist without an explicit flush");

const task = normalizeTask({ id: "task", title: "Original" })!;
saveTasks("/one", [task]);
saveTasks("/two", [{ ...task, title: "Other repository" }]);
saveTasks("/one", [{ ...task, title: "Latest edit" }]);
assert.equal(loadTasks("/one")[0].title, "Latest edit");
assert.equal(loadTasks("/two")[0].title, "Other repository");
await fileStore.flush();
assert.equal(writes.filter((write) => write.key === taskStorageKey("/one")).length, 1);
assert.equal(writes.filter((write) => write.key === taskStorageKey("/two")).length, 1);
assert.ok(writes.every((write) => !write.value?.includes('"/two":')), "Repository tasks must not share one serialized map");

fail = true;
saveTasks("/one", [{ ...task, sandboxHtml: "<h1>Unsaved sandbox</h1>" }]);
await assert.rejects(fileStore.flush(), /Synthetic disk failure/);
await assert.rejects(fileStore.flush(), /Synthetic disk failure/, "An idle failed write must not be reported as durable");
fail = false;
saveTasks("/one", [task]);
await fileStore.flush();
assert.equal(loadTasks("/one")[0].title, "Original");
const beforeSandboxPatch = writes.length;
saveTasks("/one", [{ ...task, title: "Pending metadata" }]);
fileStore.acceptTaskSandbox(taskStorageKey("/one"), task.id, "<h1>Committed</h1>", 2000);
assert.equal(loadTasks("/one")[0].title, "Pending metadata");
assert.equal(loadTasks("/one")[0].sandboxHtml, "<h1>Committed</h1>");
assert.equal(loadTasks("/one")[0].updatedAt, 2000);
assert.equal(writes.length, beforeSandboxPatch, "Receiving a committed sandbox must not start a write");
await fileStore.flush();
assert.equal(JSON.parse(writes.at(-1)!.value!)[0].sandboxHtml, "<h1>Committed</h1>");
assert.equal(JSON.parse(writes.at(-1)!.value!)[0].title, "Pending metadata");
const afterSandboxPatch = writes.length;
fileStore.acceptTaskSandbox(taskStorageKey("/two"), task.id, "<p>Background repository</p>", 3000);
assert.equal(loadTasks("/two")[0].sandboxHtml, "<p>Background repository</p>");
assert.equal(loadTasks("/two")[0].updatedAt, 3000);
await fileStore.flush();
assert.equal(writes.length, afterSandboxPatch, "A background cache patch is already persisted natively");
fileStore.setJSON("chaoticreview.removed", { pending: true });
fileStore.removeItem("chaoticreview.removed");
await fileStore.flush();
assert.equal(fileStore.getItem("chaoticreview.removed"), null);
assert.equal(writes.at(-1)?.value, null);
console.log("PASS: deferred serialization, coalesced writes, repository isolation, explicit flush, autosave, disk failure and retry.");
